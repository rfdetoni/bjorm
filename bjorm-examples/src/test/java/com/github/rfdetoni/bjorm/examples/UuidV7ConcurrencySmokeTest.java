package com.github.rfdetoni.bjorm.examples;

import com.github.rfdetoni.bjorm.UuidV7;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;
import java.util.UUID;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.Future;

/**
 * Correctness stress, not a comparative throughput benchmark.
 * Validates cross-thread uniqueness, v7 bit layout and per-thread monotonic order.
 */
public final class UuidV7ConcurrencySmokeTest {
    private static void check(boolean valid,String message) {
        if(!valid)throw new AssertionError(message);
    }
    public static void main(String[] args)throws Exception {
        final int threads=8;
        final int perThread=6_000;
        Set<UUID> seen=ConcurrentHashMap.newKeySet();
        CountDownLatch start=new CountDownLatch(1);
        List<Future<?>> futures=new ArrayList<>();
        long begin=System.nanoTime();
        try(ExecutorService pool=Executors.newFixedThreadPool(threads)) {
            for(int thread=0;thread<threads;thread++) {
                futures.add(pool.submit(()->{
                    try {start.await();}
                    catch(InterruptedException error) {Thread.currentThread().interrupt();throw new IllegalStateException(error);}
                    long previousMsb=Long.MIN_VALUE;
                    for(int i=0;i<perThread;i++) {
                        UUID uuid=UuidV7.next();
                        check(uuid.version()==7 && uuid.variant()==2,"RFC 9562 v7 version/variant");
                        long msb=uuid.getMostSignificantBits();
                        check(msb>previousMsb,"UUID v7 generated by one thread is monotonically ordered");
                        previousMsb=msb;
                        check(seen.add(uuid),"UUID v7 collision across concurrent threads");
                    }
                }));
            }
            start.countDown();
            for(Future<?> future:futures)future.get();
        }
        check(seen.size()==threads*perThread,"every concurrent UUID is unique");
        long elapsed=System.nanoTime()-begin;
        System.out.printf("PASS: UUIDv7 %d concurrent IDs / %d threads; wall time %.2f ms (diagnostic only)%n",
            seen.size(),threads,elapsed/1_000_000.0);
    }
}
