package com.github.rfdetoni.bjorm.examples;

import java.util.UUID;

/** Demonstrates opt-in ID policy without altering inferred 0.x behavior. */
public final class IdStrategySmokeTest {
    private static void check(boolean valid,String message) {if(!valid)throw new AssertionError(message);}
    public static void main(String[] args) {
        var assigned=ExplicitAssignedRecord_BjormMapper.INSTANCE;
        check(!assigned.generatedId(),"ASSIGNED numeric ID cannot be treated as SQL identity");
        check(assigned.insertSql().contains("(id, label) VALUES (?, ?)"),
            "ASSIGNED Long ID is included in INSERT");
        check(assigned.materializeInsert(new ExplicitAssignedRecord(null,"as-is")).id()==null,
            "ASSIGNED ID is never auto-generated");

        var uuid=ExplicitUuidRecord_BjormMapper.INSTANCE;
        check(!uuid.generatedId(),"UUID_V7 is generated in application, not JDBC identity");
        var record=uuid.materializeInsert(new ExplicitUuidRecord(null,"fresh"));
        check(record.id()!=null && record.id().version()==7, "explicit UUID_V7 generated");
        UUID external=UUID.randomUUID();
        check(uuid.materializeInsert(new ExplicitUuidRecord(external,"existing")).id().equals(external),
            "explicit UUID_V7 respects caller-provided ID");

        var identity=ExplicitIdentityRecord_BjormMapper.INSTANCE;
        check(identity.generatedId(),"IDENTITY marks JDBC generated key");
        check(identity.insertSql().contains("(label) VALUES (?)") && !identity.insertSql().contains("(id,"),
            "IDENTITY excludes ID from insert");
        check(identity.materializeInsert(new ExplicitIdentityRecord(null,"new")).id()==null,
            "IDENTITY is generated by database, not Java");

        check(AutoLongRecord_BjormMapper.INSTANCE.generatedId(),
            "legacy inferred Long remains IDENTITY");
        check(AutoUuidRecord_BjormMapper.INSTANCE.materializeInsert(
            new AutoUuidRecord(null,"legacy")).id().version()==7,
            "legacy inferred UUID remains UUID_V7");
        System.out.println("PASS: explicit ID strategies with legacy inference maintained");
    }
}
